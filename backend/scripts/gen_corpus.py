# 文档级权限：all 表示全员可见，其余为部门代码（| 分隔）
ACL: dict[str, tuple[str, str]] = {
    "产品手册": ("all", "品牌中心"),
    "差旅报销制度": ("all", "财务部"),
    "客服SOP": ("all", "客服中心"),
    "数据安全规范": ("all", "信息安全委员会"),
    "经销商政策": ("channel|finance|sales", "渠道事业部"),
    "薪酬与期权计划": ("hr", "人力资源部"),
    "渠道返点细则": ("channel", "渠道事业部"),
    "客户投诉登记": ("all", "客服中心"),
}


def _with_frontmatter(name: str, content: str) -> str:
    acl, department = ACL.get(name, ("all", ""))
    return f"---\nacl: {acl}\ndepartment: {department}\n---\n\n{content.strip()}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="生成演示语料")
    parser.add_argument("--force", action="store_true", help="覆盖已存在文件")
    parser.add_argument("--out", default=str(settings.raw_dir), help="输出目录")
    args = parser.parse_args()

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    written = 0
    for name, content in DOCS.items():
        path = out_dir / f"{name}.md"
        if path.exists() and not args.force:
            print(f"跳过（已存在）：{path.name}")
            continue
        path.write_text(_with_frontmatter(name, content), encoding="utf-8")
        print(f"写入：{path.name}（{len(content)} 字）")
        written += 1

    print(f"\n完成：新增 {written} 份，目录 {out_dir}")


if __name__ == "__main__":
    main()
